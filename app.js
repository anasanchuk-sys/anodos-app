function moveSlide(direction) {
  const slides = buildPresentationSlides(getLesson());
  activeSlideIndex = Math.min(Math.max(activeSlideIndex + direction, 0), slides.length - 1);
  if (activeSlideIndex === slides.length - 1) {
    stopPresentation();
  }
  renderPresentation(getLesson());
}

function togglePresentation() {
  const slides = buildPresentationSlides(getLesson());
  if (presentationPlaying) {
    stopPresentation();
    renderPresentation(getLesson());
    return;
  }

  presentationPlaying = true;
  renderPresentation(getLesson());
  presentationTimer = window.setInterval(() => {
    if (activeSlideIndex >= slides.length - 1) {
      stopPresentation();
      renderPresentation(getLesson());
      return;
    }
    activeSlideIndex += 1;
    renderPresentation(getLesson());
  }, 5200);
}

