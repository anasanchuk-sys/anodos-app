function productWord(count) {
  const lastTwo = count % 100;
  const last = count % 10;
  if (lastTwo >= 11 && lastTwo <= 14) {
    return "продуктів";
  }
  if (last === 1) {
    return "продукт";
  }
  if (last >= 2 && last <= 4) {
    return "продукти";
  }
  return "продуктів";
}

function profileWord(count) {
  const lastTwo = count % 100;
  const last = count % 10;
  if (lastTwo >= 11 && lastTwo <= 14) {
    return "профілів";
  }
  if (last === 1) {
    return "профіль";
  }
  if (last >= 2 && last <= 4) {
    return "профілі";
  }
  return "профілів";
}

