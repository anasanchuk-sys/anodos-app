function participantRegistryRows() {
  const byEmail = new Map();

  centralParticipants.map(normalizeCentralParticipant).forEach((participant) => {
    if (participant.email) {
      byEmail.set(participant.email, participant);
    }
  });

  localParticipantRows().forEach((participant) => {
    const previous = byEmail.get(participant.email);
    if (!previous) {
      byEmail.set(participant.email, participant);
      return;
    }
    const centralTime = Date.parse(previous.updatedAt || previous.lastSeenAt || previous.registeredAt || 0) || 0;
    const localTime = Date.parse(participant.updatedAt || participant.lastSeenAt || participant.registeredAt || 0) || 0;
    byEmail.set(participant.email, {
      ...(localTime >= centralTime ? previous : participant),
      ...(localTime >= centralTime ? participant : previous),
      source: "mixed"
    });
  });

  return Array.from(byEmail.values()).sort((first, second) => {
    const secondTime = Date.parse(second.updatedAt || second.lastSeenAt || second.registeredAt || 0) || 0;
    const firstTime = Date.parse(first.updatedAt || first.lastSeenAt || first.registeredAt || 0) || 0;
    return secondTime - firstTime || first.fullName.localeCompare(second.fullName, "uk");
  });
}

