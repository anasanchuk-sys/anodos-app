function normalizeSemanticText(value) {
  return String(value || "")
    .toLocaleLowerCase("uk-UA")
    .replace(/[’‘`´]/g, "'")
    .replace(/ґ/g, "г");
}

function splitSearchTerms(value) {
  return normalizeSemanticText(value)
    .split(/[^0-9a-zа-яіїєґ]+/giu)
    .map((term) => term.trim())
    .filter((term) => term.length > 2 || /^\d{3}$/.test(term));
}

function uniqueTerms(terms) {
  return [...new Set(terms.map(normalizeSemanticText).filter(Boolean))];
}

function munichQueryProfile() {
  const normalizedQuery = normalizeSemanticText(munichSearchTerm);
  const terms = new Set(splitSearchTerms(munichSearchTerm));
  const labels = new Set();

  munichSearchClusters.forEach((cluster) => {
    if (cluster.triggers.some((trigger) => normalizedQuery.includes(normalizeSemanticText(trigger)))) {
      labels.add(cluster.label);
      cluster.terms.forEach((term) => terms.add(normalizeSemanticText(term)));
    }
  });

  return {
    terms: uniqueTerms([...terms]).sort((a, b) => b.length - a.length),
    labels: [...labels]
  };
}

function munichClauseLabel(clause) {
  return `${clause.number}. ${clause.title}`;
}

function munichClauseSearchText(clause) {
  if (!clause.searchText) {
    clause.searchText = normalizeSemanticText([
      clause.number,
      clause.title,
      ...(clause.paragraphs || [])
    ].join(" "));
  }
  return clause.searchText;
}

function scoreMunichClause(clause, profile) {
  if (!profile.terms.length) {
    return 1;
  }

  const haystack = munichClauseSearchText(clause);
  const title = normalizeSemanticText(clause.title);
  let score = 0;

  profile.terms.forEach((term) => {
    if (!term) {
      return;
    }
    if (clause.number === term) {
      score += 50;
    }
    if (title.includes(term)) {
      score += 8;
    }
    if (haystack.includes(term)) {
      const matches = haystack.split(term).length - 1;
      score += Math.min(matches, 5);
    }
  });

  return score;
}

function filteredMunichClauses() {
  const profile = munichQueryProfile();
  const scored = munichClauses().map((clause) => ({
    clause,
    score: scoreMunichClause(clause, profile)
  }));

  if (!profile.terms.length) {
    return scored;
  }

  return scored
    .filter((result) => result.score > 0)
    .sort((first, second) => second.score - first.score || Number(first.clause.number) - Number(second.clause.number));
}

