function normalizeLawText(value) {
  return String(value).toLocaleLowerCase("uk-UA");
}

function lawTerms() {
  return lawSearchTerm
    .trim()
    .split(/\s+/)
    .map(normalizeLawText)
    .filter(Boolean);
}

function entryLabel(entry) {
  if (entry.type === "article") {
    return `Стаття ${entry.number}. ${entry.title}`;
  }
  return entry.title;
}

function entryMatches(entry, terms) {
  if (!terms.length) {
    return true;
  }
  const haystack = lawSearchText(entry);
  return terms.every((term) => haystack.includes(term));
}

function lawSearchText(entry) {
  if (!entry.searchText) {
    entry.searchText = normalizeLawText([
      entry.number,
      entry.title,
      entry.section,
      ...(entry.paragraphs || [])
    ].join(" "));
  }
  return entry.searchText;
}

function filteredLawEntries() {
  const terms = lawTerms();
  return lawEntries().filter((entry) => entryMatches(entry, terms));
}

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function highlightLawText(value, terms) {
  const safe = escapeHtml(value);
  if (!terms.length) {
    return safe;
  }
  const pattern = terms.map(escapeRegExp).filter(Boolean).join("|");
  if (!pattern) {
    return safe;
  }
  return safe.replace(new RegExp(`(${pattern})`, "giu"), "<mark>$1</mark>");
}

