function evaluateTaskAnswer(task, rawAnswer) {
  const answer = normalizeAnswerText(rawAnswer);
  const criteria = taskCriteriaFor(task);
  const matched = criteria.filter((criterion) =>
    criterion.terms.some((term) => answer.includes(normalizeAnswerText(term)))
  );
  const missed = criteria.filter((criterion) => !matched.includes(criterion));
  const expectedNumbers = numberFingerprints(task.answer);
  const answerNumbers = numberFingerprints(rawAnswer);
  const numberMatched = expectedNumbers.some((expected) =>
    answerNumbers.some((actual) => actual.includes(expected.slice(0, Math.min(expected.length, 7))) || expected.includes(actual.slice(0, Math.min(actual.length, 7))))
  );
  const completeness = criteria.length ? matched.length / criteria.length : 0;
  const score = Math.min(100, Math.round(completeness * 82 + (numberMatched ? 18 : 0)));

  let level = "Потребує доопрацювання";
  if (score >= 86) {
    level = "Сильна відповідь";
  } else if (score >= 65) {
    level = "Добра основа";
  } else if (score >= 42) {
    level = "Часткова відповідь";
  }

  return {
    score,
    level,
    matched: matched.map((item) => item.label),
    missed: missed.map((item) => item.label),
    numberMatched,
    text: rawAnswer
  };
}

