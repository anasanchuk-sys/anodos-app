function render() {
  const user = currentUser();
  if (!isAuthorizedUser(user)) {
    body.dataset.route = "registration";
    if (currentUserId) {
      clearCurrentUser();
    }
    body.classList.add("registration-mode");
    progressValue.textContent = "0%";
    document.querySelectorAll(".nav-item").forEach((button) => {
      button.classList.remove("nav-item-active");
    });
    renderRegistration();
    return;
  }

  body.classList.remove("registration-mode");
  body.dataset.route = route;
  progressValue.textContent = `${totalProgress()}%`;
  document.querySelectorAll(".nav-item").forEach((button) => {
    button.classList.toggle("nav-item-active", button.dataset.route === route);
  });

  if (route === "module") {
    renderModule(getLesson());
    return;
  }

  if (route === "module-section") {
    renderModuleSection(getLesson(), activeModuleSectionId);
    return;
  }

  if (route === "contract-auth") {
    renderContractAccess(getLesson());
    return;
  }

  if (route === "quiz") {
    renderQuiz(getLesson());
    return;
  }

  if (route === "law-quiz") {
    renderLawQuiz(getLesson());
    return;
  }

  if (route === "presentation") {
    renderPresentation(getLesson());
    return;
  }

  if (route === "contract") {
    renderContractTemplateViewer(getContractTemplate());
    return;
  }

  if (route === "sources") {
    renderSources();
    return;
  }

  if (route === "law") {
    renderLaw();
    return;
  }

  if (route === "munich") {
    renderMunichClauses();
    return;
  }

  if (route === "glossary") {
    renderGlossary();
    return;
  }

  if (route === "editor") {
    renderEditor(getLesson());
    return;
  }

  if (route === "progress") {
    renderProgress();
    return;
  }

  renderHome();
}

