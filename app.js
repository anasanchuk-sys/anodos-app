function isEditableElement(target) {
  return Boolean(target?.closest?.("input, textarea, select, [contenteditable='true'], .law-article"));
}

function isContractViewerElement(target) {
  return Boolean(target?.closest?.(".contract-viewer-panel"));
}

function isHomeRoute() {
  return body.dataset.route === "home";
}

function lockStaticUiElements() {
  document.querySelectorAll("a, button, img, svg, video").forEach((element) => {
    element.setAttribute("draggable", "false");
  });
}

function markOpeningModule(button) {
  if (prefersReducedMotion) {
    return;
  }
  const card = button?.closest?.(".module-card");
  if (!card) {
    return;
  }
  card.classList.add("module-card-opening");
  window.setTimeout(() => {
    card.classList.remove("module-card-opening");
  }, 220);
}

function openModuleButton(button) {
  const lessonId = button?.dataset?.openModule;
  if (!lessonId) {
    return;
  }

  contractAccessGranted = false;
  pendingContractTemplateId = "";
  contractPasswordError = "";
  activeModuleSectionId = "";
  markOpeningModule(button);
  setRoute("module", lessonId);

  window.setTimeout(() => {
    if (route === "module" && activeLessonId === lessonId) {
      return;
    }
    pendingRoute = "";
    pendingLessonId = "";
    body.classList.remove("route-is-changing");
    screen.classList.remove("screen-transition-out", "screen-transition-in");
    applyRouteState("module", lessonId);
  }, 160);
}

function openModuleSectionButton(button) {
  const sectionId = button?.dataset?.openModuleSection;
  const lessonId = button?.dataset?.moduleSectionLesson || activeLessonId;
  if (!sectionId) {
    return;
  }

  activeModuleSectionId = sectionId;
  if (sectionId === "contracts" && !contractAccessGranted) {
    contractPasswordError = "";
    setRoute("contract-auth", lessonId);
    return;
  }

  setRoute("module-section", lessonId);

  window.setTimeout(() => {
    if (route === "module-section" && activeLessonId === lessonId && activeModuleSectionId === sectionId) {
      return;
    }
    pendingRoute = "";
    pendingLessonId = "";
    body.classList.remove("route-is-changing");
    screen.classList.remove("screen-transition-out", "screen-transition-in");
    applyRouteState("module-section", lessonId);
  }, 160);
}

