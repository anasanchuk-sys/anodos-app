document.addEventListener("submit", async (event) => {
  if (event.target.id === "adminRegistryForm") {
    event.preventDefault();
    const formData = new FormData(event.target);
    const password = String(formData.get("adminPassword") || "").trim();
    if (password !== contractAccessPassword) {
      adminPasswordError = "Невірний пароль адміністратора.";
      render();
      window.scrollTo(0, 0);
      return;
    }

    adminRegistryUnlocked = true;
    adminPasswordError = "";
    await refreshCentralParticipants({ renderAfter: true });
    window.scrollTo(0, 0);
    return;
  }

  if (event.target.id === "registrationForm") {
    event.preventDefault();
    const formData = new FormData(event.target);
    const fullName = String(formData.get("fullName") || "").trim();
    const email = normalizeEmail(formData.get("email"));

    if (!isBritmarkEmail(email)) {
      loginError = "Вхід доступний лише з робочої пошти @britmark.com.";
      render();
      window.scrollTo(0, 0);
      return;
    }

    let user = registeredUsers.find((item) => normalizeEmail(item.email) === email);
    if (user) {
      user.fullName = fullName || user.fullName;
      user.email = email;
      user.lastSeenAt = new Date().toISOString();
      delete user.organization;
      delete user.role;
    } else {
      user = {
        id: createUserId(),
        fullName,
        email,
        registeredAt: new Date().toISOString(),
        lastSeenAt: new Date().toISOString()
      };
      registeredUsers.push(user);
    }

    loginError = "";
    saveRegisteredUsers();
    setCurrentUser(user.id);
    void syncCurrentParticipant("login");
    route = "home";
    render();
    window.scrollTo(0, 0);
    return;
  }

  if (event.target.id === "contractAccessForm") {
    event.preventDefault();
    const formData = new FormData(event.target);
    const password = String(formData.get("contractPassword") || "").trim();
    if (password !== contractAccessPassword) {
      contractPasswordError = "Невірний пароль.";
      renderContractAccess(getLesson());
      return;
    }

    contractAccessGranted = true;
    contractPasswordError = "";

    if (pendingContractTemplateId) {
      const templateId = pendingContractTemplateId;
      pendingContractTemplateId = "";
      openContractTemplate(templateId);
      return;
    }

    activeModuleSectionId = "contracts";
    setRoute("module-section", activeLessonId);
    return;
  }

  if (event.target.id === "profileEditForm") {
    event.preventDefault();
    const user = currentUser();
    if (!user) {
      return;
    }

    const formData = new FormData(event.target);
    const nextEmail = normalizeEmail(formData.get("email"));
    if (!isBritmarkEmail(nextEmail)) {
      loginError = "Профіль можна зберегти лише з робочою поштою @britmark.com.";
      profileEditMode = true;
      render();
      window.scrollTo(0, 0);
      return;
    }

    user.fullName = String(formData.get("fullName") || "").trim();
    user.email = nextEmail;
    delete user.organization;
    delete user.role;
    const photoFile = formData.get("photo");
    const photo = await profilePhotoFromFile(photoFile);
    if (photo) {
      user.photo = photo;
    }
    user.lastSeenAt = new Date().toISOString();
    loginError = "";
    saveRegisteredUsers();
    void syncCurrentParticipant("profile");
    profileEditMode = false;
    render();
    window.scrollTo(0, 0);
    return;
  }

  if (event.target.id === "lawQuizForm") {
    event.preventDefault();
    const item = getLesson();
    const test = item.lawTests;
    if (!test?.quiz?.length) {
      return;
    }

    const formData = new FormData(event.target);
    let correct = 0;

    test.quiz.forEach((question, index) => {
      const value = formData.get(`q${index}`);
      const selected = value === null ? null : Number(value);
      quizAnswers[index] = selected;
      if (selected === question.answer) {
        correct += 1;
      }
    });

    quizResult = {
      correct,
      score: Math.round((correct / test.quiz.length) * 100)
    };

    renderLawQuiz(item);
    return;
  }

  if (event.target.id === "quizForm") {
    event.preventDefault();
    const item = getLesson();
    const formData = new FormData(event.target);
    let correct = 0;

    item.quiz.forEach((question, index) => {
      const value = formData.get(`q${index}`);
      const selected = value === null ? null : Number(value);
      quizAnswers[index] = selected;
      if (selected === question.answer) {
        correct += 1;
      }
    });

    quizResult = {
      correct,
      score: Math.round((correct / item.quiz.length) * 100)
    };

    progress[item.id] = {
      score: quizResult.score,
      done: quizResult.score >= item.threshold,
      updatedAt: new Date().toISOString()
    };
    saveCurrentProgress();
    progressValue.textContent = `${totalProgress()}%`;
    renderQuiz(item);
    return;
  }

  if (event.target.id === "editorForm") {
    event.preventDefault();
    const formData = new FormData(event.target);
    editorDrafts[activeLessonId] = {
      title: formData.get("title"),
      outcome: formData.get("outcome"),
      briefing: formData.get("briefing")
    };
    writeJson(editorKey, editorDrafts);
    renderEditor(getLesson());
  }
});

