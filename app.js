function moduleSectionDefinitions(item, briefing) {
  const sections = [];

  if (item.articles?.length) {
    sections.push({
      id: "articles",
      title: "Статті",
      meta: `${item.articles.length} матеріалів BritMark`,
      content: renderArticleCards(item)
    });
  }

  if (item.contractTemplates?.length) {
    sections.push({
      id: "contracts",
      title: "Шаблони договорів",
      meta: `${item.contractTemplates.length} шаблони`,
      content: renderContractTemplateCards(item)
    });
  }

  sections.push({
    id: "video",
    title: "Відео-презентація",
    meta: item.video.runtime || "матеріал",
    content: renderVideoContent(item)
  });

  if (briefing.length) {
    sections.push({
      id: "briefing",
      title: "Короткий конспект",
      meta: `${briefing.length} тези`,
      content: renderBriefingCards(briefing)
    });
  }

  if (item.tasks?.length) {
    sections.push({
      id: "tasks",
      title: "Задачі",
      meta: `${item.tasks.length} кейсів`,
      content: renderTaskCards(item)
    });
  }

  if (item.lawTests?.quiz?.length) {
    sections.push({
      id: "law-tests",
      title: "Тести до ЗУпС",
      meta: `${item.lawTests.quiz.length} питань`,
      content: renderLawTestsContent(item)
    });
  }

  const clauses = munichClauses();
  if (item.id === "construction" && clauses.length) {
    sections.push({
      id: "munich",
      title: "Застереження Munich Re",
      meta: `${clauses.length} застереження · пошук`,
      directAction: "munich"
    });
  }

  sections.push({
    id: "test",
    title: "Тест",
    meta: `${item.threshold}% для проходження`,
    content: renderTestContent(item)
  });

  return sections;
}

