  async function buildBlob(result) {
    if (!result?.sections?.length) {
      throw new Error("Спочатку підготуйте опитувальник.");
    }
    const [docx, logo] = await Promise.all([ensureDocxLibrary(), logoBytes()]);
    const documentFile = buildDocument(docx, result, logo);
    return docx.Packer.toBlob(documentFile);
  }

  async function download(result) {
    const blob = await buildBlob(result);
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = filenameFor(result);
    document.body.append(link);
    link.click();
    link.remove();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
    return { filename: filenameFor(result), size: blob.size, type: blob.type || DOCX_MIME };
  }

