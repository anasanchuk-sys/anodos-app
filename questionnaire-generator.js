  function safeFilenamePart(value) {
    return normalizeSubject(value)
      .replace(/[\\/:*?"<>|]/g, "")
      .replace(/[^\p{L}\p{N}._ -]+/gu, "")
      .replace(/\s+/g, "_")
      .slice(0, 72) || "ризик";
  }

